import { describe, expect, test } from "vitest";
import { normalizePrice } from "./price";

describe("normalizePrice", () => {
  test.each([
    ["半角の数字はそのまま", "1200", "1200"],
    ["全角の数字は半角に直す", "１２００", "1200"],
    ["全角と半角が混ざっていても半角にそろえる", "１2０0", "1200"],
    ["カンマと「円」を取り除く", "1,200円", "1200"],
    ["全角のカンマ・円記号も取り除く", "￥１，２００", "1200"],
    ["前後の空白を取り除く", " 980 ", "980"],
    ["マイナスは取り除く（価格は 0 円以上）", "-500", "500"],
    ["空欄は空欄のまま", "", ""],
    ["数字がなければ空欄になる", "わからない", ""],
    ["7 桁はそのまま", "1234567", "1234567"],
    ["8 桁以上は先頭の 7 桁だけ残す", "12345678", "1234567"],
    ["記号を取り除いてから 7 桁にそろえる", "1,234,567円", "1234567"],
  ])("%s（%s → %s）", (_, value, expected) => {
    const actual = normalizePrice(value);

    expect(actual).toBe(expected);
  });
});
